"""Prompts and JSON schemas for question generation and judging.

The train and test prompts are written differently on purpose (and are run by
models of different families), so that the style of training questions does not
leak into the test set.
"""

QUESTION_TYPES = ("everyday", "search", "legal")

# ---------------------------------------------------------------- train (Qwen3)

TRAIN_SYSTEM = (
    "Ты помогаешь собрать обучающие данные для поисковой системы по законам РФ. "
    "По тексту статьи закона ты придумываешь вопросы, которые задали бы реальные люди, "
    "и ответ на которые содержится в этой статье. Отвечай только JSON."
)

TRAIN_USER = """Текст (фрагмент закона):
<<<
{header}
{text}
>>>

Придумай три разных вопроса, ответ на которые есть в этом тексте:
1. "everyday": бытовая ситуация обычного человека от первого лица, простыми словами,
без юридических терминов (1-2 предложения).
2. "search": короткий поисковый запрос из 3-7 слов, как в поисковике, без вопросительного знака.
3. "legal": вопрос юриста, с профессиональной терминологией.

Правила:
- не упоминай номер статьи, главы или пункта и название закона;
- не пиши «согласно статье», «в данной статье», «по этому закону»;
- не копируй фразы из текста: не больше 4 слов подряд, пересказывай своими словами;
- вопросы должны быть про разные аспекты текста, если это возможно."""

TRAIN_SCHEMA = {
    "type": "object",
    "properties": {t: {"type": "string", "minLength": 5, "maxLength": 400} for t in QUESTION_TYPES},
    "required": list(QUESTION_TYPES),
    "additionalProperties": False,
}

# ---------------------------------------------------------------- dev/test (YandexGPT)

TEST_TYPE_INSTRUCTIONS = {
    "everyday": (
        "Опиши жизненную ситуацию человека, который не знает законов, и задай его вопрос. "
        "Пиши разговорным языком, от первого лица, без юридических слов. Одно-два предложения."
    ),
    "search": (
        "Напиши короткий запрос в поисковую строку: от 3 до 7 слов, без знаков вопроса, как обычно пишут в поисковике."
    ),
    "legal": (
        "Сформулируй вопрос, который задал бы практикующий юрист коллеге. "
        "Используй точную юридическую терминологию. Одно предложение."
    ),
}

TEST_SYSTEM = "Ты составляешь тестовые вопросы для проверки системы поиска по российскому законодательству."

TEST_USER = """Вот положение закона.

{header}
{text}

Задание: {instruction}

Ответ на вопрос должен находиться в этом положении. Номер статьи и название закона не называй, \
текст положения дословно не цитируй. Верни JSON с полем "question"."""

TEST_SCHEMA = {
    "type": "object",
    "properties": {"question": {"type": "string", "minLength": 5, "maxLength": 400}},
    "required": ["question"],
    "additionalProperties": False,
}

# ---------------------------------------------------------------- judge (Qwen3)

JUDGE_SYSTEM = "Ты строгий эксперт по российскому праву и проверяешь качество тестовых вопросов. Отвечай только JSON."

JUDGE_USER = """Статья закона:
<<<
{header}
{text}
>>>

Вопрос пользователя: «{question}»

Можно ли ответить на этот вопрос (полностью или по существу), опираясь на эту статью? \
Ответь "yes" или "no" в поле "answerable"."""

JUDGE_SCHEMA = {
    "type": "object",
    "properties": {"answerable": {"type": "string", "enum": ["yes", "no"]}},
    "required": ["answerable"],
    "additionalProperties": False,
}
